#!/usr/bin/env python3
"""Embed web/*.html sources into Arduino PROGMEM header files."""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

TARGETS = {
    ROOT / "web" / "relay": ROOT / "pHloat_Relay" / "web_ui_templates.h",
    ROOT / "web" / "sensor": ROOT / "pHloat_Sensor" / "web_ui_templates.h",
}


def c_escape(content: str) -> str:
    return content.replace("\\", "\\\\").replace('"', '\\"')


def embed_dir(src_dir: Path, out_file: Path) -> None:
    html_files = sorted(src_dir.glob("*.html"))
    if not html_files:
        raise SystemExit(f"No HTML files in {src_dir}")

    lines = [
        "// Auto-generated by scripts/embed_web_ui.py — edit web/*.html and re-run.",
        "#pragma once",
        "",
    ]

    for html_path in html_files:
        const_name = "TPL_" + html_path.stem.upper()
        body = html_path.read_text(encoding="utf-8")
        lines.append(f"static const char {const_name}[] PROGMEM = R\"PHOAT({body})PHOAT\";")
        lines.append("")

    out_file.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out_file} ({len(html_files)} templates)")


def main() -> None:
    for src, out in TARGETS.items():
        embed_dir(src, out)


if __name__ == "__main__":
    main()
